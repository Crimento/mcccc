const knownTraitCodes = new Set(personalityTraitOptions.map(option => option.value))
const knownPetTraitCodes = new Set(petTraitOptions.map(option => option.value))

// Only known traits may be changed. Unknown/modded IDs and every unrelated raw
// token retain their exact whitespace, duplicates, position, and string form.
export function toggleKnownTrait(current: string, code: string, selected: boolean): string {
  return toggleTrait(current, code, selected, knownTraitCodes)
}

export function toggleKnownPetTrait(current: string, code: string, selected: boolean): string {
  return toggleTrait(current, code, selected, knownPetTraitCodes)
}

function toggleTrait(current: string, code: string, selected: boolean, knownCodes: ReadonlySet<string>): string {
  if (!knownCodes.has(code)) return current
  const tokens = current.split(',')
  if (selected) {
    if (tokens.some(token => token.trim() === code)) return current
    return current === '' ? code : `${current},${code}`
  }
  return tokens.filter(token => token.trim() !== code).join(',')
}
